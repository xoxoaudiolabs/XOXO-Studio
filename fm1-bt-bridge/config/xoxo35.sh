#!/usr/bin/env bash
# The Studio's 3.5" touchscreen overlay, xoxo35: Raspberry Pi OS's piscreen overlay (the same ILI9486 + XPT2046 on
# the same pins: its touch, rotate, speed and fps as they are) with the panel's start-up set to the screen maker's,
# goodtft's (LCD-show's tft35a overlay): VCOM 00 91 80 00 in place of piscreen's 0, and its power and timing
# settings. With piscreen's the Hosyond 3.5" showed the backlight through and its blacks washed out; with these
# the blacks are blacker and the near-black steps still show (picked by eye on the Studio with a test card,
# 2026-11-02).
# Usage: xoxo35.sh PISCREEN_DTBO OUT_DTBO   (needs dtc: device-tree-compiler)
set -euo pipefail
INIT='init = <0x10000f1 0x36 0x04 0x00 0x3c 0x0f 0x8f 0x10000f2 0x18 0xa3 0x12 0x02 0xb2 0x12 0xff 0x10 0x00 0x10000f8 0x21 0x04 0x10000f9 0x00 0x08 0x1000036 0x08 0x10000b4 0x00 0x10000c1 0x41 0x10000c5 0x00 0x91 0x80 0x00 0x10000e0 0x0f 0x1f 0x1c 0x0c 0x0f 0x08 0x48 0x98 0x37 0x0a 0x13 0x04 0x11 0x0d 0x00 0x10000e1 0x0f 0x32 0x2e 0x0b 0x0d 0x05 0x47 0x75 0x37 0x06 0x10 0x03 0x24 0x20 0x00 0x100003a 0x55 0x1000011 0x1000036 0x28 0x20000ff 0x1000029>;'
src=$(dtc -q -I dtb -O dts "$1")
[ "$(grep -c 'init = <' <<<"$src")" = 1 ] || { echo "xoxo35: piscreen's overlay isn't as expected" >&2; exit 1; }
sed "s/init = <[^>]*>;/$INIT/" <<<"$src" | dtc -q -@ -I dts -O dtb -o "$2"
